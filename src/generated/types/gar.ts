/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/** Дочерний объект (дом, квартира, земельный участок и т.д.). */
export interface GarChildItem {
  /** Числовой идентификатор. */
  objectId: number;
  /** UUID (GUID) объекта. */
  objectGuid: string;
  /** Отображаемое имя (например, "д. 5 корп. 1", "кв. 18"). */
  displayName: string;
  /** Тип объекта ("дом", "квартира", "комната", "зем.участок", "машино-место", "адр.объект"). */
  objectType: string;
  /**
   * Тип объекта из справочника ГАР AS_HOUSE_TYPES, краткой формой:
   * «д.» (дом), «гар.» (гараж), «влд.» (владение), «зд.» (здание),
   * «д.влд.» (домовладение). Пусто у участков, машино-мест, помещений и
   * адресообразующих объектов — у них своего справочника типов нет.
   */
  houseType: string;
  /** Почтовый индекс (если доступен, для домов). */
  postalCode: string;
}

/** Ответ со списком дочерних объектов. */
export interface GarChildrenResponse {
  /** Идентификатор родительского объекта. */
  parentObjectId: number;
  /** Список дочерних объектов. */
  children: GarChildItem[];
  /** Общее количество дочерних объектов. */
  count: number;
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/** Элемент иерархии адреса (один уровень пути от объекта к региону). */
export interface GarHierarchyItem {
  /** Числовой идентификатор объекта. */
  objectId: number;
  /** Отображаемое имя объекта (например, "ул Ленина", "д. 5"). */
  displayName: string;
}

/** Ответ с иерархией объекта (путь от корня до объекта). */
export interface GarHierarchyResponse {
  /** Идентификатор запрошенного объекта. */
  objectId: number;
  /** Путь в иерархии от корня (региона) к объекту. */
  path: GarHierarchyItem[];
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/** Детальная информация об одном объекте ГАР. */
export interface GarObjectDetailsResponse {
  /** Числовой идентификатор объекта. */
  objectId: number;
  /** UUID (GUID) объекта. */
  objectGuid: string;
  /** Полный адрес объекта (из иерархии). */
  fullAddress: string;
  /** Тип объекта. */
  objectType: string;
  /** Код региона (2 цифры). */
  regionCode: string;
  /** Иерархия: путь от корня (региона) к данному объекту. */
  hierarchy: GarHierarchyItem[];
  /**
   * Параметры объекта (индекс, ОКТМО, ОКАТО, ИФНС, КЛАДР и т.д.).
   * Параметры наследуются от предков, если у объекта своих нет.
   */
  parameters: GarParamEntry[];
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/** Параметр объекта ГАР (индекс, ОКТМО, ОКАТО, КЛАДР, ИФНС и т.д.). */
export interface GarParamEntry {
  /** Тип параметра (числовой идентификатор из справочника AS_PARAM_TYPES). */
  typeId: number;
  /** Расшифровка типа параметра (например, "Почтовый индекс", "ОКТМО"). */
  typeName: string;
  /** Значение параметра (строка, формат зависит от типа). */
  value: string;
}

/** Информация о регионе (субъекте РФ). */
export interface GarRegionInfo {
  /** Код региона (2 цифры, например "77"). */
  code: string;
  /** Наименование региона (например, "Москва", "Самарская обл"). */
  name: string;
  /** Числовой идентификатор объекта региона в ГАР. */
  objectId: number;
}

/** Статистика по конкретному региону (субъекту РФ). */
export interface GarRegionStatsResponse {
  /** Код региона (2 цифры). */
  regionCode: string;
  /** Наименование региона. */
  regionName: string;
  /** Количество адресных объектов в регионе. */
  addressObjectCount: number;
  /** Количество домов в регионе. */
  houseCount: number;
  /** Количество квартир/помещений в регионе. */
  apartmentCount: number;
  /** Количество комнат в регионе. */
  roomCount: number;
  /** Количество земельных участков в регионе. */
  steadCount: number;
  /** Количество машино-мест в регионе. */
  carplaceCount: number;
  /**
   * Количество нежилых помещений: офисы, склады, цеха, торговые залы, павильоны,
   * подвалы, котельные, погреба, рабочие участки и помещения без уточнения типа.
   */
  nonResidentialCount: number;
  /** Количество гаражей. */
  garageCount: number;
  /** Количество объектов, тип которых в реестре не указан. */
  unknownTypeCount: number;
  /**
   * Полная разбивка по каноническим типам объектов: «квартира», «комната»,
   * «помещение», «гараж» и так далее, как их отдаёт геокодер.
   */
  breakdown: Record<string, number>;
  /** Общее количество объектов реестра всех типов в регионе. */
  totalObjectCount: number;
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/** Ответ на поисковый запрос: список результатов с метаданными. */
export interface GarSearchResponse {
  /** Исходная строка запроса. */
  query: string;
  /** Список найденных адресных объектов. */
  results: GarSearchResult[];
  /** Количество найденных результатов. */
  count: number;
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/**
 * Один результат поиска адреса в ГАР.
 * Содержит полный адрес, идентификаторы и ключевые параметры объекта.
 */
export interface GarSearchResult {
  /**
   * Полный адрес объекта, построенный из иерархии (PATH).
   * Пример: "Самарская обл, г Самара, ул Ленина, д. 5"
   */
  fullAddress: string;
  /** Тип объекта: "адр.объект", "дом", "квартира", "комната", "зем.участок", "машино-место". */
  objectType: string;
  /**
   * UUID (GUID) объекта в ГАР.
   * Аналог AOGUID/HOUSEGUID из старого ФИАС.
   */
  objectGuid: string;
  /** Числовой идентификатор объекта (стабильный, не меняется при обновлении). */
  objectId: number;
  /** Двузначный код региона (например, "77" = Москва, "63" = Самарская обл.). */
  regionCode: string;
  /** Почтовый индекс (6 цифр), если доступен. */
  postalCode: string;
  /** Код ОКТМО (8 или 11 цифр), если доступен. */
  oktmo: string;
  /** Код ОКАТО (до 11 цифр), если доступен. */
  okato: string;
}

