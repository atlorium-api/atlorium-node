/**
 * Типы запросов и ответов сервиса «API погодных данных».
 *
 * СГЕНЕРИРОВАНО scripts/generate.mjs — не редактировать руками. Источник: spec/weather_ru.json.
 */

/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/** Облачность. */
export interface Clouds {
  /** Доля неба, закрытая облаками, в процентах: 0 — ясно, 100 — сплошная облачность. */
  all: number;
}

/** Географические координаты точки. */
export interface Coord {
  /** Долгота в градусах, от −180 (запад) до +180 (восток). */
  lon: number;
  /** Широта в градусах, от −90 (Южный полюс) до +90 (Северный полюс). */
  lat: number;
}

/** Основные измеримые показатели погоды. */
export interface Main {
  /** Температура воздуха в градусах Цельсия. */
  temp: number;
  /**
   * Ощущаемая температура в градусах Цельсия — с поправкой на ветер и влажность.
   * Именно её показывают человеку: при −5 °C и сильном ветре ощущается как −12 °C.
   */
  feels_like: number;
  /** Атмосферное давление на уровне моря в гектопаскалях (гПа). Норма — около 1013. */
  pressure: number;
  /** Относительная влажность воздуха в процентах. */
  humidity: number;
  /**
   * Минимальная температура по территории в градусах Цельсия. Для крупных городов
   * расходится с temp: в разных районах измерения отличаются.
   */
  temp_min: number;
  /** Максимальная температура по территории в градусах Цельсия. */
  temp_max: number;
  /** Давление на уровне моря в гПа. null — если измерение недоступно. */
  sea_level: number | null;
  /**
   * Давление на уровне земли в гПа — с поправкой на высоту точки над уровнем моря.
   * null — если измерение недоступно.
   */
  grnd_level: number | null;
}

/**
 * Объём осадков. Заполняется только то поле, по которому есть измерение,
 * поэтому оба значения могут быть null одновременно.
 */
export interface Precipitation {
  /** Объём осадков за последний час, в миллиметрах. */
  '1h': number | null;
  /** Объём осадков за последние три часа, в миллиметрах. */
  '3h': number | null;
}

/** Сведения о стране и о времени восхода и заката. */
export interface Sys {
  /** Служебный признак типа станции наблюдения. Прикладного смысла не несёт. */
  type: number | null;
  /** Служебный идентификатор станции наблюдения. */
  id: number | null;
  /** Служебный параметр метеорологической сводки. Прикладного смысла не несёт. */
  message: number | null;
  /** Код страны по стандарту ISO 3166-1 alpha-2: RU, KZ, DE. */
  country: string;
  /**
   * Время восхода солнца в формате Unix-времени (секунды, UTC). Для местного времени
   * точки прибавьте timezone.
   */
  sunrise: number;
  /** Время заката солнца в формате Unix-времени (секунды, UTC). */
  sunset: number;
}

/** Одно погодное явление: код, короткое имя, описание и иконка. */
export interface Weather {
  /**
   * Код явления. Диапазон задаёт группу: 2xx — гроза, 3xx — морось, 5xx — дождь,
   * 6xx — снег, 7xx — атмосферные явления (туман, дымка, пыль), 800 — ясно,
   * 80x — облачность. Ветвиться в коде надёжнее по этому числу, чем по тексту описания.
   */
  id: number;
  /** Короткое название группы явления на английском: Rain, Clouds, Clear. */
  main: string;
  /** Описание явления на русском языке: «небольшой дождь», «переменная облачность». */
  description: string;
  /**
   * Код иконки явления, например 10d или 04n. Последняя буква — время суток:
   * d — день, n — ночь. Картинка по коду отдаётся эндпоинтом иконок.
   */
  icon: string;
}

/**
 * Текущая погода в точке с указанными координатами: температура, ветер, облачность,
 * осадки и время восхода/заката.
 *
 * Единицы измерения во всём ответе метрические: температура в градусах Цельсия,
 * скорость ветра в метрах в секунду, давление в гектопаскалях. Текстовые описания
 * приходят на русском языке.
 */
export interface WeatherData {
  /** Координаты точки, для которой отдана погода. */
  coord: Coord;
  /**
   * Погодные явления в точке. Как правило один элемент, но при сочетании явлений
   * (например, дождь с грозой) их может быть несколько — основным считается первый.
   */
  weather: Weather[];
  /**
   * Служебная пометка метеорологической службы. Прикладного смысла
   * не несёт, оставлена для полноты ответа.
   */
  base: string;
  /** Основные измеримые показатели: температура, давление, влажность. */
  main: Main;
  /**
   * Дальность видимости в метрах. Максимальное значение — 10 000 (десять километров),
   * дальше метеостанции не измеряют. null — если измерение недоступно.
   */
  visibility: number | null;
  /** Ветер: скорость, направление и порывы. */
  wind: Wind;
  /** Облачность. */
  clouds: Clouds;
  /**
   * Объём выпавшего дождя. null — если дождя нет; поле в этом случае просто отсутствует,
   * а не приходит нулём.
   */
  rain: Precipitation | null;
  /** Объём выпавшего снега. null — если снега нет. */
  snow: Precipitation | null;
  /**
   * Момент, на который актуальны данные, в формате Unix-времени (секунды с 1 января 1970
   * года, UTC). Пример: 1 700 000 000 — это 14 ноября 2023 года, 22:13 UTC.
   * Чтобы получить местное время точки, прибавьте timezone.
   */
  dt: number;
  /** Сведения о стране и о времени восхода и заката. */
  sys: Sys;
  /**
   * Сдвиг местного времени точки относительно UTC в секундах. Для Москвы — 10800
   * (плюс три часа). Отрицательное значение — часовой пояс западнее Гринвича.
   */
  timezone: number;
  /** Идентификатор населённого пункта в справочнике метеорологических станций. */
  id: number;
  /**
   * Название ближайшего населённого пункта. Для точки в поле или в море может не совпадать
   * с ожидаемым: выбирается ближайшая известная точка наблюдения.
   */
  name: string;
  /**
   * Служебный код метеорологической сводки (200 — успех). На HTTP-код ответа API
   * не влияет: при сбое сервис вернёт собственный код и тело ошибки.
   */
  cod: number;
}

/** Характеристики ветра. */
export interface Wind {
  /** Скорость ветра в метрах в секунду. */
  speed: number;
  /**
   * Направление, ОТКУДА дует ветер, в градусах по часовой стрелке от севера:
   * 0 — северный, 90 — восточный, 180 — южный, 270 — западный.
   */
  deg: number;
  /** Скорость порывов в метрах в секунду. null — если порывов нет или они не измерялись. */
  gust: number | null;
}
