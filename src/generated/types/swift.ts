/**
 * Типы запросов и ответов сервиса «API справочника SWIFT/BIC».
 *
 * СГЕНЕРИРОВАНО scripts/generate.mjs — не редактировать руками. Источник: spec/swift_ru.json.
 */

/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/**
 * Почтовый адрес организации в структурированном виде. Используется для адресов, вынесенных
 * отдельным блоком (например, адрес штаб-квартиры). Любое поле может быть null: в справочнике
 * адрес заполнен не всегда полностью.
 */
export interface SwiftAddress {
  /** Улица/дом/корпус — все содержательные строки адреса, объединённые через запятую. */
  address: string | null;
  /** Город. */
  city: string | null;
  /** Регион/субъект (например, "DE-HE"). */
  region: string | null;
  /** Код страны в формате ISO-3166 alpha-2 (например, "DE"). */
  country: string | null;
  /** Почтовый индекс. */
  postalCode: string | null;
  /** Номер дома/строения (поле addressNumber). Заполняется редко; null, если нет. */
  addressNumber: string | null;
  /** Номер помещения/офиса внутри здания (поле addressNumberWithinBuilding). null, если нет. */
  addressNumberWithinBuilding: string | null;
  /**
   * Готовая почтовая строка для конвертов: индекс, город и адрес одной строкой.
   * Заполняется не всегда; null, если строка недоступна.
   */
  mailRouting: string | null;
  /**
   * Язык адреса (ISO-639, например "ru"/"en"). Полезно для адресов на других языках
   * (см. otherAddresses). null для основного адреса.
   */
  language: string | null;
  /**
   * Тип адреса для альтернативных адресов: например "ALTERNATIVE_LANGUAGE_LEGAL_ADDRESS" —
   * юридический адрес на другом языке, "...HEADQUARTERS_ADDRESS" — адрес штаб-квартиры на другом языке.
   * null для основного юр. адреса/адреса штаб-квартиры.
   */
  type: string | null;
}

/**
 * Карточка одной организации из справочника SWIFT/BIC одним плоским набором полей.
 * Объединяет идентификаторы организации (SWIFT/BIC, LEI), её юридическое наименование
 * и адрес, а также признаки актуальности данных.
 *
 *
 * Пример. По коду DEUTDEFF в карточке будет: Name = "DEUTSCHE BANK
 * AKTIENGESELLSCHAFT", Country = "DE", City = "Frankfurt am Main", Lei = 20-значный код,
 * EntityStatus = "ACTIVE", а в allBics — все BIC этой организации (у крупных
 * банков их десятки, по одному на страну/филиал).
 */
export interface SwiftBankInfo {
  /**
   * Основной SWIFT/BIC-код организации (8 или 11 символов). При точечном поиске по BIC сюда
   * попадает запрошенный код; при поиске по названию — первый из кодов организации (или null,
   * если у организации в справочнике нет ни одного привязанного SWIFT/BIC).
   */
  bic: string | null;
  /**
   * LEI — Legal Entity Identifier, 20-значный международный идентификатор юридического лица
   * (стандарт ISO 17442). Уникален для организации и удобен как «сквозной» ключ при сверке
   * контрагентов между разными системами.
   */
  lei: string;
  /** Юридическое наименование организации. */
  name: string;
  /**
   * Прочие наименования организации: торговые марки, сокращённые названия, написания на других
   * языках/в другой транслитерации. Пусто, если у организации зарегистрировано только одно имя.
   * Полезно при сверке контрагента, который в платёжке указан не «официальным» именем.
   */
  otherNames: string[];
  /** Код страны юридического адреса в формате ISO-3166 alpha-2 (например, "DE", "RU"). */
  country: string | null;
  /**
   * Код юрисдикции регистрации организации (ISO-3166, например "DE" или субкод вида "US-DE").
   * Обычно совпадает со страной адреса, но не всегда — поэтому возвращается отдельным полем.
   */
  jurisdiction: string | null;
  /**
   * Категория организации: например "GENERAL" — обычное юр. лицо, "FUND" — фонд,
   * "BRANCH" — филиал, "SOLE_PROPRIETOR" — ИП. Возвращается в исходном виде справочника.
   */
  entityCategory: string | null;
  /**
   * Подкатегория организации (поле subCategory): уточняет категорию для отдельных типов
   * (например, виды фондов). Заполняется редко; null, если не указана.
   */
  entitySubCategory: string | null;
  /**
   * Код организационно-правовой формы (ELF — Entity Legal Form, стандарт ISO 20275; например
   * "6QQB" для немецкой AG). Это машинный код формы; null, если форма не указана.
   */
  legalForm: string | null;
  /** Город юридического адреса. */
  city: string | null;
  /** Регион/субъект юридического адреса (например, "DE-HE" — Гессен). */
  region: string | null;
  /** Почтовый индекс юридического адреса. */
  postalCode: string | null;
  /**
   * Юридический адрес одной строкой — все содержательные строки адреса (улица, дом, корпус),
   * объединённые через запятую. Город/регион/индекс/страна вынесены в отдельные поля.
   */
  address: string | null;
  /**
   * Адрес штаб-квартиры (фактического головного офиса). Часто совпадает с юридическим адресом,
   * но у международных групп может отличаться, поэтому возвращается отдельной структурой.
   * null, если штаб-квартира не указана.
   */
  headquarters: SwiftAddress | null;
  /**
   * Идентификатор регистрирующего органа, в котором организация внесена в реестр (код вида
   * "RA000242" — например, для Германии это торговый реестр Handelsregister). null, если не указан.
   */
  registrationAuthorityId: string | null;
  /**
   * Регистрационный номер организации в этом органе (например, "HRB 30000" — номер в немецком
   * торговом реестре). Это локальный номер юр. лица в его стране, аналог ОГРН для РФ. null, если нет.
   */
  registrationId: string | null;
  /** Дата создания (учреждения) юридического лица (UTC). null, если неизвестна. */
  entityCreationDate: string | null;
  /** Дата прекращения существования организации (UTC). null — организация не прекращена/неизвестно. */
  entityExpirationDate: string | null;
  /**
   * Причина прекращения существования (поле expiration.reason): например "DISSOLVED" —
   * ликвидирована, "CORPORATE_ACTION" — реорганизация. null, если организация не прекращена.
   */
  entityExpirationReason: string | null;
  /**
   * LEI ассоциированной организации (поле associatedEntity.lei): для фондов — управляющая компания
   * и т.п. null, если ассоциированной организации нет.
   */
  associatedEntityLei: string | null;
  /** Наименование ассоциированной организации (associatedEntity.name). См. associatedEntityLei. */
  associatedEntityName: string | null;
  /**
   * Статус юридического лица: "ACTIVE" — действует, "INACTIVE" — ликвидировано/присоединено.
   * Позволяет потребителю отличать действующие организации от прекративших существование.
   */
  entityStatus: string | null;
  /**
   * Статус актуальности регистрационной записи: "ISSUED" — актуальна и подтверждена,
   * "LAPSED" — не продлевалась (данные могли устареть), "RETIRED"/"MERGED" — закрыта.
   * Возвращается в исходном виде справочника — по нему оценивают свежесть регистрационных сведений.
   */
  registrationStatus: string | null;
  /** Дата последнего обновления регистрационной записи (UTC). null, если неизвестна. */
  lastUpdate: string | null;
  /** Дата первичной регистрации записи об организации в реестре (UTC). null, если неизвестна. */
  initialRegistrationDate: string | null;
  /**
   * Дата, до которой запись подтверждена и подлежит следующему продлению (UTC). Если она в прошлом,
   * а статус не "ISSUED" — данные могли устареть (организация не продлевала регистрацию). null, если нет.
   */
  nextRenewalDate: string | null;
  /**
   * Идентификатор организации, которая ведёт (поддерживает) эту регистрационную запись —
   * 20-значный код по тому же стандарту, что и LEI. Технический реквизит регистрационной записи.
   */
  managingLou: string | null;
  /**
   * Уровень подтверждённости данных записи: "FULLY_CORROBORATED" — полностью сверены с официальным
   * реестром, "PARTIALLY_CORROBORATED"/"ENTITY_SUPPLIED_ONLY" — подтверждены частично/со слов организации.
   * Помогает оценить степень доверия к карточке. Возвращается в исходном виде справочника.
   */
  corroborationLevel: string | null;
  /**
   * Идентификатор органа, по данным которого ПОДТВЕРЖДАЛАСЬ запись (validatedAt.id). Обычно совпадает
   * с registrationAuthorityId, но может отличаться. null, если не указан.
   */
  validationAuthorityId: string | null;
  /** Номер организации в органе подтверждения (validatedAs). См. validationAuthorityId. */
  validationId: string | null;
  /**
   * Признак соответствия записи политике качества данных (conformityFlag): "CONFORMING" —
   * соответствует, "NON_CONFORMING" — нет. null, если не указан.
   */
  conformityFlag: string | null;
  /** Служебный код качества регистрационной записи. Технический реквизит. null, если нет. */
  qualityCode: string | null;
  /**
   * История юридических событий организации (слияния, смена адреса/наименования и т.п.) из блока
   * eventGroups. Пусто, если событий нет. Позволяет проследить значимые изменения по датам.
   */
  legalEvents: SwiftLegalEvent[];
  /**
   * Готовая почтовая строка юридического адреса (поле mailRouting): индекс, город и адрес одной
   * строкой, как принято в стране организации. Например: "117997, г. Москва, ул. Вавилова, д. 19".
   * Заполняется не всегда; null, если строка недоступна.
   */
  mailRouting: string | null;
  /**
   * Альтернативные адреса организации — прежде всего адрес на другом языке (например, английская
   * версия юр. адреса/адреса штаб-квартиры для российских организаций). У каждого адреса заполнены
   * type и language. Пусто, если их нет.
   */
  otherAddresses: SwiftAddress[];
  /**
   * LEI организации-правопреемника. Заполняется, когда организация прекратила существование
   * (слияние/присоединение) и её правопреемник известен. null — правопреемника нет/неизвестен.
   */
  successorLei: string | null;
  /** Наименование организации-правопреемника (если есть). См. successorLei. */
  successorName: string | null;
  /**
   * MIC — Market Identifier Code (ISO 10383), код торговой площадки. Заполнен в основном у бирж
   * и торговых систем; у обычных банков обычно null.
   */
  mic: string | null;
  /** Идентификатор организации в реестре OpenCorporates (внешняя сверка контрагентов). null, если нет. */
  openCorporatesId: string | null;
  /** Идентификаторы организации в данных S&P Global (внешняя сверка/обогащение). Пусто, если их нет. */
  spGlobalIds: string[];
  /**
   * Все SWIFT/BIC-коды, привязанные к этой организации. У международных групп их бывает много
   * (отдельный код на страну/подразделение). Пустой список — у организации нет ни одного BIC.
   */
  allBics: string[];
}

/**
 * Результат проверки формата SWIFT/BIC по стандарту ISO-9362. Считается локально, по самой
 * строке, и разбирает её на составные части. isValidFormat говорит ТОЛЬКО о
 * корректности формата, но НЕ о том, что такой код реально существует (для проверки
 * существования есть точечный поиск по BIC).
 *
 *
 * Пример. Для "DEUTDEFFXXX": IsValidFormat = true, BankCode = "DEUT", CountryCode = "DE",
 * LocationCode = "FF", BranchCode = "XXX", IsPrimaryOffice = true.
 */
export interface SwiftBicValidationResult {
  /** Нормализованный код (верхний регистр, без пробелов; 8-значный дополнен "XXX"). */
  normalizedBic: string;
  /** true, если строка соответствует формату ISO-9362 (длина и наборы символов по позициям). */
  isValidFormat: boolean;
  /** Понятное человеку пояснение результата (что именно не так с форматом, либо «формат корректен»). */
  message: string;
  /** Код организации — первые 4 буквы (позиции 1–4, institution code по ISO-9362). */
  bankCode: string | null;
  /** Код страны — позиции 5–6, буквы ISO-3166 alpha-2. */
  countryCode: string | null;
  /** Код местоположения — позиции 7–8 (буквы или цифры). Вторая цифра "1" обычно означает пассивного участника. */
  locationCode: string | null;
  /**
   * Код филиала — позиции 9–11 (опционально). "XXX" или отсутствие означает головной офис.
   * null, если на вход пришёл 8-значный код (без явного филиала).
   */
  branchCode: string | null;
  /** true, если код относится к головному офису (филиал отсутствует или равен "XXX"). */
  isPrimaryOffice: boolean;
}

/**
 * Юридическое событие в истории организации:
 * слияние/поглощение, смена юридического адреса, наименования и т.п.
 */
export interface SwiftLegalEvent {
  /**
   * Тип события: например "MERGERS_AND_ACQUISITIONS" — слияние/поглощение,
   * "CHANGE_LEGAL_ADDRESS" — смена юр. адреса, "CHANGE_LEGAL_NAME" — смена наименования.
   */
  type: string | null;
  /** Статус события: например "COMPLETED" — завершено, "IN_PROGRESS" — в процессе. */
  status: string | null;
  /** Дата вступления события в силу (UTC). null, если не указана. */
  effectiveDate: string | null;
  /** Дата, когда событие зафиксировано в реестре (UTC). null, если не указана. */
  recordedDate: string | null;
}

/** Ответ на поиск по справочнику SWIFT/BIC: найденные организации и параметры запроса. */
export interface SwiftSearchResponse {
  /** Исходная строка запроса — возвращается без изменений. */
  query: string;
  /** Найденные организации (текущая страница ответа, не больше запрошенного limit). */
  results: SwiftBankInfo[];
  /** Количество элементов в results (на текущей странице). */
  count: number;
  /**
   * Сколько всего организаций соответствует запросу. Может быть больше count:
   * в ответ кладётся лишь первая страница (limit), а здесь — полный размер совпадения.
   * По нему строится подпись вида «показано 20 из 134».
   */
  totalMatches: number;
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/** Состояние сервиса справочника SWIFT/BIC: готов ли он отвечать на запросы. */
export interface SwiftStatsResponse {
  /** Готов ли сервис отвечать на запросы (для справочника SWIFT/BIC — практически всегда true). */
  isReady: boolean;
}

/** Необязательные параметры метода `search`. */
export interface SearchParams {
  /** Максимум результатов (по умолчанию 20, максимум 100). */
  limit?: number;
}
