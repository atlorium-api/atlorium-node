/**
 * Типы запросов и ответов сервиса «API ЕГРЮЛ/ЕГРИП».
 *
 * СГЕНЕРИРОВАНО scripts/generate.mjs — не редактировать руками. Источник: spec/egrul_ru.json.
 */

/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/**
 * Учредитель (участник) организации. Заполняется для ЮЛ из официальной выписки, поэтому может
 * быть доступен не для всех организаций (например, состав участников банков/АО в реестре
 * раскрывается не всегда). Если данных нет — список учредителей у карточки будет пустым.
 */
export interface CompanyFounder {
  /** Тип учредителя: физическое лицо, российское/иностранное юридическое лицо, государство и т.п. */
  kind: string | null;
  /** Наименование ЮЛ-учредителя или ФИО физлица-учредителя. */
  name: string;
  /** ИНН учредителя (если раскрыт). Иначе пусто. */
  inn: string | null;
  /** Номинальная стоимость доли в рублях (если раскрыта). Иначе пусто. */
  shareNominal: number | null;
  /** Размер доли в процентах (если раскрыт). Иначе пусто. */
  sharePercent: number | null;
}

/**
 * Тип субъекта, на который выдана карточка.
 *
 * Значения:
 * * `Unknown` — Тип не определён (например, ничего не найдено по запросу).
 * * `LegalEntity` — Юридическое лицо (ЮЛ, ЕГРЮЛ): ООО, АО, ПАО, НКО и т.п.
 * * `SoleProprietor` — Индивидуальный предприниматель (ИП, ЕГРИП), включая главу КФХ.
 */
export type CompanyKind = 'Unknown' | 'LegalEntity' | 'SoleProprietor';

/**
 * Полная карточка организации одним плоским набором полей.
 * Объединяет реквизиты, статус, адрес, руководителя/учредителей, капитал, виды
 * деятельности, сведения о регистрирующем/налоговом органе, налоговые режимы и данные о МСП.
 *
 *
 * Какие поля заполнены — зависит от kind:
 * для ЮЛ заполняются КПП, уставный капитал, руководитель, способ образования; для ИП — ФИО и
 * (если раскрыты в выписке) e-mail, пол, гражданство. Неприменимые поля остаются пустыми.
 */
export interface CompanyLookupResult {
  /**
   * true, если организация найдена по переданному идентификатору. false означает, что по
   * ИНН/ОГРН ничего не нашлось (опечатка либо такого субъекта нет в реестре) — в этом случае
   * остальные поля карточки пустые.
   */
  found: boolean;
  /** Тип субъекта: юридическое лицо (ЕГРЮЛ) или индивидуальный предприниматель (ЕГРИП). */
  kind: CompanyKind;
  /** ИНН (10 цифр у ЮЛ, 12 у ИП/физлица). */
  inn: string | null;
  /** ОГРН (13 цифр у ЮЛ) или ОГРНИП (15 цифр у ИП). */
  ogrn: string | null;
  /** КПП — только для ЮЛ (9 цифр). У ИП всегда пусто. */
  kpp: string | null;
  /**
   * Полное наименование: для ЮЛ — полное фирменное наименование ("ПУБЛИЧНОЕ АКЦИОНЕРНОЕ
   * ОБЩЕСТВО \"СБЕРБАНК РОССИИ\""), для ИП — ФИО предпринимателя.
   */
  fullName: string | null;
  /** Сокращённое наименование ЮЛ ("ПАО СБЕРБАНК"). У ИП обычно совпадает с ФИО или пусто. */
  shortName: string | null;
  /** Организационно-правовая форма (ОКОПФ), код. Только для ЮЛ. Иначе пусто. */
  legalFormCode: string | null;
  /** Текстовый статус: "Действующая организация", "Деятельность прекращена" и т.п. */
  status: string | null;
  /** true, если субъект действующий (не ликвидирован/не прекратил деятельность). */
  active: boolean;
  /** Дата присвоения ОГРН/ОГРНИП (государственной регистрации). */
  registrationDate: string | null;
  /**
   * Дата первичной регистрации до 01.07.2002 — только для «старых» ЮЛ, созданных до введения
   * ЕГРЮЛ. Иначе пусто.
   */
  registrationDateBefore2002: string | null;
  /** Дата постановки на учёт в налоговом органе. */
  taxRegistrationDate: string | null;
  /** Дата, на которую актуальны сведения карточки (дата формирования данных). */
  dataDate: string | null;
  /** Юридический адрес одной строкой ("117312, Г.МОСКВА, УЛ. ВАВИЛОВА, Д.19"). Для ИП пусто. */
  address: string | null;
  /** Почтовый индекс адреса (если есть). */
  postalCode: string | null;
  /** Код региона (субъекта РФ), например "77". */
  regionCode: string | null;
  /** Наименование региона, например "Г.МОСКВА". */
  regionName: string | null;
  /** Наименование регистрирующего органа (где зарегистрирован субъект). */
  registrationAuthority: string | null;
  /** Код регистрирующего органа. */
  registrationAuthorityCode: string | null;
  /** Наименование налогового органа (где субъект состоит на учёте). */
  taxAuthority: string | null;
  /** Код налогового органа. */
  taxAuthorityCode: string | null;
  /** Основной вид деятельности по ОКВЭД (код + наименование). Иначе пусто. */
  primaryOkved: CompanyOkved | null;
  /**
   * Тип сведений об основном ОКВЭД: "отчётный" или "заявительный" (как именно эти сведения
   * попали в реестр). Иначе пусто.
   */
  primaryOkvedType: string | null;
  /** Дополнительные виды деятельности по ОКВЭД. Может быть пустым списком. */
  additionalOkveds: CompanyOkved[];
  /** Размер уставного капитала в рублях. Только для ЮЛ. Иначе пусто. */
  authorizedCapital: number | null;
  /** Вид капитала ("УСТАВНЫЙ КАПИТАЛ", "СКЛАДОЧНЫЙ КАПИТАЛ" и т.п.). Только для ЮЛ. */
  capitalType: string | null;
  /** Способ образования ЮЛ ("Создание юридического лица до 01.07.2002" и т.п.). Только для ЮЛ. */
  formationMethod: string | null;
  /** Лица, имеющие право действовать без доверенности (руководители). Обычно один. Только для ЮЛ. */
  managers: CompanyManager[];
  /**
   * Учредители (участники). Заполняется из официальной выписки и может отсутствовать для части
   * организаций — тогда список пуст. Только для ЮЛ.
   */
  founders: CompanyFounder[];
  /** Фамилия ИП. Только для ИП. */
  lastName: string | null;
  /** Имя ИП. Только для ИП. */
  firstName: string | null;
  /** Отчество ИП (при наличии). Только для ИП. */
  middleName: string | null;
  /** Гражданство ИП (например, "гражданин Российской Федерации"). Если раскрыто. */
  citizenship: string | null;
  /** Пол ИП ("мужской"/"женский"), если раскрыт в выписке. Иначе пусто. */
  gender: string | null;
  /** Адрес электронной почты, если он указан в выписке. Иначе пусто. */
  email: string | null;
  /**
   * Применяемые специальные налоговые режимы (по последним доступным сведениям): например
   * "УСН", "ЕСХН", "ПСН", "НПД", "АУСН". Пустой список — спецрежимов не выявлено / общий режим.
   */
  specialTaxRegimes: string[];
  /**
   * Категория в реестре малого и среднего предпринимательства (МСП): "Микропредприятие",
   * "Малое предприятие", "Среднее предприятие". Пусто, если субъект не числится в реестре МСП.
   */
  smeCategory: string | null;
  /** Дата включения в реестр МСП (если применимо). */
  smeRegistryDate: string | null;
  /** Публикации в «Вестнике государственной регистрации» (для ЮЛ). Может быть пуст. */
  publications: CompanyPublication[];
  /**
   * Признак «массового адреса»: по юридическому адресу зарегистрировано много других организаций.
   * Косвенный фактор риска при проверке контрагента. Для ИП всегда false.
   */
  massAddress: boolean;
  /**
   * true, если по субъекту доступна официальная выписка из реестра в PDF (её можно скачать
   * отдельным запросом — см. метод выгрузки выписки в API).
   */
  officialExcerptAvailable: boolean;
  /**
   * Предупреждения о качестве данных: например, если какое-то поле не удалось надёжно
   * сопоставить при сборке карточки. Пустой список означает, что замечаний нет.
   */
  warnings: string[];
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/**
 * Лицо, имеющее право действовать от имени организации без доверенности (руководитель).
 * Для ЮЛ это, как правило, директор/генеральный директор/президент.
 */
export interface CompanyManager {
  /** ФИО руководителя, например "ГРЕФ ГЕРМАН ОСКАРОВИЧ". */
  fullName: string;
  /** ИНН руководителя (если раскрыт). Иначе пусто. */
  inn: string | null;
  /** Должность, например "ПРЕЗИДЕНТ, ПРЕДСЕДАТЕЛЬ ПРАВЛЕНИЯ". Иначе пусто. */
  position: string | null;
}

/** Вид экономической деятельности по классификатору ОКВЭД-2: код + расшифровка. */
export interface CompanyOkved {
  /** Код вида деятельности, например "62.01". */
  code: string;
  /** Наименование вида деятельности, например "Разработка компьютерного программного обеспечения". */
  name: string;
}

/** Запись о публикации сведений об организации в журнале «Вестник государственной регистрации». */
export interface CompanyPublication {
  /** Код типа публикации (служебный). */
  code: number;
  /** Количество публикаций данного типа. */
  count: number;
  /** Ссылка на публикацию. */
  url: string | null;
}

/**
 * Краткая карточка субъекта для результатов поиска по наименованию/ФИО (когда по запросу может
 * найтись несколько организаций). По выбранному элементу затем запрашивается полная карточка.
 */
export interface CompanySearchItem {
  /** Тип субъекта: юридическое лицо (ЕГРЮЛ) или ИП (ЕГРИП). */
  kind: CompanyKind;
  /** ИНН субъекта. */
  inn: string | null;
  /** ОГРН/ОГРНИП субъекта. */
  ogrn: string | null;
  /** Наименование ЮЛ или ФИО ИП. */
  name: string;
  /** Текстовый статус (например, "Действующая организация"). */
  status: string | null;
  /** Регион (если известен). */
  region: string | null;
  /** Основной вид деятельности по ОКВЭД (если известен). */
  primaryOkved: string | null;
}

/** Ответ на поиск по наименованию/ФИО: список кратких карточек + сколько всего найдено. */
export interface CompanySearchResponse {
  /** Исходный поисковый запрос (как его передал клиент). */
  query: string;
  /** Найденные субъекты (ограничено лимитом запроса). */
  results: CompanySearchItem[];
  /** Сколько результатов вернулось в этом ответе. */
  count: number;
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/** Необязательные параметры метода `get`. */
export interface GetParams {
  /**
   * Расширенные сведения из официальной выписки, которых нет в базовой карточке: у ИП —
   * адрес электронной почты и пол; у ЮЛ — состав участников/учредителей и их доли. По умолчанию
   * false (выключено). Включение требует дополнительной обработки выписки, поэтому ответ может
   * формироваться дольше.
   */
  extended?: boolean;
}

/** Необязательные параметры метода `search`. */
export interface SearchParams {
  /** Максимум результатов (по умолчанию 10, максимум 50). */
  limit?: number;
}
