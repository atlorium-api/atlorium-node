/**
 * Типы запросов и ответов сервиса «API валидации телефона».
 *
 * СГЕНЕРИРОВАНО scripts/generate.mjs — не редактировать руками. Источник: spec/phone_ru.json.
 */

/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/**
 * Результат базового (офлайн) разбора номера: всё, что известно о номере из справочника
 * мировой нумерации, без единого обращения в сеть.
 */
export interface PhoneNumberInfo {
  /**
   * true, если номер валиден: он не просто похож на телефон по длине, но и попадает в реально
   * выделенный диапазон своей страны. Именно это поле стоит использовать как «номер годен».
   */
  isValid: boolean;
  /**
   * true, если номер лишь ПОХОЖ на телефонный (подходящая длина для своей страны), но при этом
   * может не попадать ни в один выделенный диапазон. Более мягкая проверка, чем isValid:
   * полезна, когда справочник нумерации страны отстаёт от реальности и настоящий номер помечен
   * невалидным. Если false — это точно не телефон.
   */
  isPossible: boolean;
  /**
   * Номер в международном формате E.164 — канонический вид без пробелов и скобок
   * (например, "+79161234567"). Именно эту форму следует хранить в своей базе.
   * Пусто, если номер не удалось разобрать.
   */
  e164: string | null;
  /**
   * Номер в международном формате для показа человеку, с разделителями
   * (например, "+7 916 123-45-67"). Пусто, если номер не удалось разобрать.
   */
  international: string | null;
  /**
   * Номер в национальном формате записи, принятом в его стране
   * (например, "8 (916) 123-45-67"). Пусто, если номер не удалось разобрать.
   */
  national: string | null;
  /**
   * Номер в формате RFC 3966 — как ссылка для набора (например, "tel:+7-916-123-45-67").
   * Удобно подставлять в атрибут href. Пусто, если номер не удалось разобрать.
   */
  rfc3966: string | null;
  /** Телефонный код страны без плюса (например, 7 для России, 1 для США). 0 — если не определён. */
  countryCallingCode: number;
  /**
   * Код страны номера в формате ISO-3166 alpha-2 (например, "RU"). Пусто, если страну определить
   * не удалось. Для кодов, общих у нескольких стран (например, +7 у России и Казахстана,
   * +1 у США и Канады), страна определяется по последующим цифрам номера.
   */
  countryCode: string | null;
  /** Название страны номера на русском языке (например, "Россия"). Пусто, если не определено. */
  country: string | null;
  /** Тип номера, определённый по его диапазону в справочнике нумерации. */
  numberType: PhoneNumberKind;
  /**
   * Оператор, которому ВЫДЕЛЕН диапазон номера (например, "МТС").
   *
   *
   * ВНИМАНИЕ, ЭТО НЕ ОБЯЗАТЕЛЬНО ОПЕРАТОР АБОНЕНТА. Здесь возвращается оператор ДИАПАЗОНА —
   * тот, кому этот диапазон номеров выделен изначально. С 2013 года абонент вправе перенести
   * номер к другому оператору, сохранив его (MNP, «мобильное рабство» отменено). Справочник
   * нумерации о переносах не знает и знать не может: сведения о том, кто обслуживает
   * КОНКРЕТНЫЙ номер сегодня, есть только у сети оператора. Доля перенесённых номеров в России
   * исчисляется миллионами, поэтому для номера, выбранного наугад, это поле — обоснованная
   * догадка, а не факт. Не принимайте по нему решений, требующих точного знания оператора
   * (например, тарификацию звонков или выбор SMS-маршрута).
   * Пусто, если оператор диапазона неизвестен или неприменим (например, для стационарных номеров).
   */
  originalCarrier: string | null;
  /**
   * Географическая привязка ДИАПАЗОНА номера: город, регион или страна — насколько подробно
   * позволяет справочник (например, "Москва и Московская область"). Это место, к которому
   * приписан диапазон, а не местоположение абонента: владелец мобильного номера физически может
   * находиться где угодно. Пусто, если не определена.
   */
  location: string | null;
  /**
   * Часовые пояса, к которым относится диапазон номера, в формате базы IANA (например,
   * "Europe/Moscow"). Обычно один, но у номеров больших стран их может быть несколько.
   * Пусто, если не определены.
   */
  timeZones: string[];
}

/**
 * Тип телефонного номера, определённый по его диапазону в справочнике нумерации.
 * Значения передаются в JSON строкой: "Mobile", а не 1.
 *
 * Значения:
 * * `Unknown` — Тип определить не удалось (справочник не знает такого диапазона).
 * * `Mobile` — Мобильный номер.
 * * `FixedLine` — Стационарный (городской) номер.
 * * `FixedLineOrMobile` — Диапазон, в котором стационарные и мобильные номера не разделены. Так устроена нумерация в ряде стран (например, в США), поэтому отличить одно от другого по справочнику невозможно.
 * * `TollFree` — Бесплатный для звонящего номер (8-800 и мировые аналоги).
 * * `PremiumRate` — Номер с повышенной тарификацией звонка (premium rate).
 * * `SharedCost` — Номер с разделением платы между звонящим и принимающим (shared cost).
 * * `Voip` — Номер IP-телефонии (VoIP).
 * * `PersonalNumber` — Персональный номер, переадресуемый абонентом на любой другой.
 * * `Pager` — Пейджер.
 * * `Uan` — Универсальный номер доступа (UAN), обычно корпоративный.
 * * `Voicemail` — Голосовая почта.
 */
export type PhoneNumberKind = 'Unknown' | 'Mobile' | 'FixedLine' | 'FixedLineOrMobile' | 'TollFree' | 'PremiumRate' | 'SharedCost' | 'Voip' | 'PersonalNumber' | 'Pager' | 'Uan' | 'Voicemail';

/** Полная карточка результата проверки телефонного номера одним плоским набором полей. */
export interface PhoneReport {
  /** Номер в том виде, в каком он был передан в запросе. */
  input: string;
  /** Результат офлайн-разбора номера. Заполняется всегда. */
  number: PhoneNumberInfo;
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/** Необязательные параметры метода `validate`. */
export interface ValidateParams {
  /**
   * Код страны (ISO-3166 alpha-2, например "RU"), в которой трактовать номер, записанный
   * в национальном формате. Для номеров с «+» не нужен и игнорируется.
   */
  countryCode?: string;
}
