/** Контакт для жалоб на злоупотребления с адреса (abuse-контакт владельца сети). */
export interface AbuseInfo {
  /** Имя ответственного лица или название подразделения, принимающего жалобы. */
  name: string | null;
  /**
   * Адрес электронной почты для жалоб — основной канал: именно сюда пишут о спаме,
   * переборе паролей и сканировании с этого адреса.
   */
  email: string | null;
  /** Телефон для связи, если владелец сети его опубликовал. */
  phone: string | null;
  /** Почтовый адрес владельца сети из регистрационных данных. */
  address: string | null;
  /** Страна владельца сети. Может не совпадать со страной самого адреса. */
  country: string | null;
  /** Диапазон сети, к которому относится контакт. */
  network: string | null;
}

/** Отметка о жалобах на адрес по публичным базам репутации. */
export interface AbuseReportsInfo {
  /** true — на адрес есть публичные жалобы (флаг «замечен в злоупотреблениях»). */
  flagged: boolean;
  /** Ссылка на публичную страницу с деталями жалоб (если есть). */
  detailsUrl: string | null;
}

/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/** Сведения об автономной системе (ASN). */
export interface AsnInfo {
  /** Номер AS в формате «AS12345». */
  asn: string | null;
  /** Название оператора AS. */
  name: string | null;
  /** Домен оператора. */
  domain: string | null;
  /** Анонсируемый префикс (маршрут), которому принадлежит адрес. */
  route: string | null;
  /** Тип AS: isp / hosting / business / education и т.п. */
  type: string | null;
  /** Статус RPKI маршрута (валиден ли ROA), если известно. */
  rpkiValid: boolean | null;
  /** Когда сведения об ASN последний раз менялись (если известно). */
  lastChanged: string | null;
}

/** Данные мобильного оператора (заполнены только для мобильных сетей). */
export interface CarrierInfo {
  /** Название оператора. */
  name: string | null;
  /** MCC — код страны мобильной сети. */
  mcc: string | null;
  /** MNC — код мобильной сети внутри страны. */
  mnc: string | null;
}

/** Организация-владелец диапазона. */
export interface CompanyInfo {
  /**
   * Название организации, за которой закреплён диапазон. Может отличаться от оператора
   * автономной системы: провайдер выдаёт часть своей сети клиенту, и владельцем числится клиент.
   */
  name: string | null;
  /** Сайт организации — по нему быстрее всего понять, кто это на самом деле. */
  domain: string | null;
  /** Диапазон адресов организации в нотации CIDR, например 93.184.216.0/24. */
  route: string | null;
  /** Тип организации: hosting / isp / business и т.п. */
  type: string | null;
}

/** Географические сведения об адресе. Все поля опциональны — заполняется, что известно. */
export interface GeoInfo {
  /** Населённый пункт: «Москва», «Екатеринбург». */
  city: string | null;
  /** Регион первого уровня: область, край, штат. */
  region: string | null;
  /** Код региона, например MOW или SVE. */
  regionCode: string | null;
  /** Название страны. */
  country: string | null;
  /** Код страны по стандарту ISO 3166-1 alpha-2: RU, DE, US. */
  countryCode: string | null;
  /** Название части света. */
  continent: string | null;
  /** Код части света: EU, AS, NA. */
  continentCode: string | null;
  /**
   * Широта центра предполагаемой зоны. Это НЕ адрес пользователя: точность задаётся
   * радиусом accuracyRadiusKm и обычно измеряется десятками километров.
   */
  latitude: number | null;
  /** Долгота центра предполагаемой зоны. Оговорка про точность — та же, что у широты. */
  longitude: number | null;
  /** Почтовый индекс зоны, если он известен. */
  postal: string | null;
  /** Часовой пояс в нотации IANA: Europe/Moscow, Asia/Yekaterinburg. */
  timezone: string | null;
  /** Код DMA (рекламный рынок США). Заполняется в основном для адресов в США. */
  dmaCode: string | null;
  /** Идентификатор населённого пункта в GeoNames. */
  geonameId: string | null;
  /** Радиус точности геолокации в километрах (чем меньше — тем точнее). */
  accuracyRadiusKm: number | null;
  /** Когда сведения о географии адреса последний раз менялись (если известно). */
  lastChanged: string | null;
}

/** Сведения о доменах, размещённых на адресе. */
export interface HostedDomainsInfo {
  /** Сколько доменов размещено на адресе. Возвращается только количество, без перечня доменов. */
  total: number | null;
}

/**
 * Профиль IP-адреса. Любая секция может быть пустой: набор доступных сведений зависит от
 * самого адреса (например, carrier заполняется только у мобильных сетей) и от режима запроса
 * (privacy и abuse возвращаются только в расширенном). Незаполненные секции следует
 * пропускать, а не считать ошибкой.
 */
export interface IpReport {
  /** Запрошенный IP-адрес в нормализованном виде. */
  ip: string;
  /** Какой объём сведений внутри (см. IpReportTier). */
  tier: IpReportTier;
  /** true — адрес из «служебного» диапазона (bogon): частный/зарезервированный/loopback и т.п. */
  isBogon: boolean;
  /** Обратное DNS-имя (PTR) хоста, если известно. Иначе null. */
  hostname: string | null;
  /** Основная география адреса — наиболее достоверный из доступных вариантов. Может быть null. */
  geo: GeoInfo | null;
  /**
   * Расходящиеся варианты географии, когда данные по адресу не совпадают между собой.
   * Заполняется только при расхождении: если все имеющиеся сведения сходятся, показывать
   * нечего и поле пустое. Варианты помечены нейтрально — «Источник 1», «Источник 2».
   */
  geoSources: SourcedGeo[] | null;
  /** Сведения об автономной системе (ASN) — «кто держит» сеть. Может быть null. */
  asn: AsnInfo | null;
  /** Расходящиеся варианты сведений об автономной системе. Заполняется только при расхождении, иначе null. */
  asnSources: SourcedAsn[] | null;
  /** Организация-владелец диапазона (может отличаться от ASN-оператора). Может быть null. */
  company: CompanyInfo | null;
  /** Признаки сети (хостинг/мобильный/anycast/спутник и т.п.). Может быть null. */
  flags: NetworkFlags | null;
  /** Данные мобильного оператора — только для мобильных сетей. Иначе null. */
  carrier: CarrierInfo | null;
  /** Признаки анонимизации (VPN/proxy/Tor/relay/резидентный прокси). Только расширенный режим. */
  privacy: PrivacyInfo | null;
  /** Контакт для жалоб (abuse). Только расширенный режим. Может быть null. */
  abuse: AbuseInfo | null;
  /** Сведения о доменах, размещённых на адресе (сейчас — только счётчик). Может быть null. */
  hostedDomains: HostedDomainsInfo | null;
  /** Отметка о жалобах на адрес (публичные базы репутации). Только расширенный режим. */
  abuseReports: AbuseReportsInfo | null;
}

/**
 * Объём сведений в ответе: базовый профиль или расширенный.
 *
 * Значения:
 * * `Basic` — Базовый профиль: география, автономная система, организация-владелец, hostname.
 * * `Extended` — Базовый профиль и дополнительно признаки анонимизации, контакт для жалоб, отметка о жалобах.
 */
export type IpReportTier = 'Basic' | 'Extended';

/** Признаки сети верхнего уровня. */
export interface NetworkFlags {
  /** Адрес отмечен как анонимный (обобщённый признак). */
  isAnonymous: boolean | null;
  /** Anycast-адрес (один и тот же адрес анонсируется из многих точек). */
  isAnycast: boolean | null;
  /** Адрес принадлежит хостингу/дата-центру. */
  isHosting: boolean | null;
  /** Адрес принадлежит мобильной сети. */
  isMobile: boolean | null;
  /** Спутниковый провайдер. */
  isSatellite: boolean | null;
}

/**
 * Признаки анонимизации — что известно о том, прячется ли реальный источник трафика за
 * VPN, прокси или Tor, и насколько свежий это сигнал. Возвращается в расширенном режиме.
 */
export interface PrivacyInfo {
  /**
   * Адрес принадлежит VPN-сервису. Само по себе это не признак злого умысла: VPN
   *             массово используют и для работы, и для приватности.
   */
  isVpn: boolean | null;
  /** Адрес принадлежит прокси-серверу — трафик идёт через посредника. */
  isProxy: boolean | null;
  /** Адрес — выходной узел сети Tor. Реальный источник трафика в этом случае неизвестен. */
  isTor: boolean | null;
  /**
   * Адрес относится к сервису приватной ретрансляции (например, iCloud Private Relay).
   * Формально это не VPN, но исходный адрес пользователя всё равно скрыт.
   */
  isRelay: boolean | null;
  /** Адрес относится к хостингу (частый признак «не живого» пользователя). */
  isHosting: boolean | null;
  /** Резидентный прокси (трафик прячется за адресами обычных домашних пользователей). */
  isResidentialProxy: boolean | null;
  /** Название конкретного сервиса анонимизации, если определено (например, публичный VPN/прокси-сервис). */
  serviceName: string | null;
  /** Когда адрес в последний раз наблюдался как анонимизирующий (свежесть сигнала). */
  lastSeen: string | null;
  /** Доля дней за последнюю неделю, когда адрес был активен как прокси (0..100). */
  percentDaysSeen: number | null;
}

/** Один из расходящихся вариантов сведений об автономной системе. */
export interface SourcedAsn {
  /** Нейтральная метка варианта: «Источник 1», «Источник 2». */
  sourceLabel: string;
  /** Сведения об автономной системе в этом варианте. */
  asn: AsnInfo | null;
}

/** Один из расходящихся вариантов географии адреса. */
export interface SourcedGeo {
  /** Нейтральная метка варианта: «Источник 1», «Источник 2». */
  sourceLabel: string;
  /** География адреса в этом варианте. */
  geo: GeoInfo;
}

/** Необязательные параметры метода `lookup`. */
export interface LookupParams {
  /**
   * Расширенные сведения: владелец сети (ASN/организация), hostname, признаки анонимизации
   * (VPN/прокси/Tor/relay/резидентный прокси), контакт для жалоб и отметка о жалобах. По
   * умолчанию false. Расширенный режим тарифицируется по собственной цене — см. страницу тарифов.
   */
  extended?: boolean;
}
