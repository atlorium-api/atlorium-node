/**
 * Типы запросов и ответов сервиса «API BIN Lookup».
 *
 * СГЕНЕРИРОВАНО scripts/generate.mjs — не редактировать руками. Источник: spec/bin_ru.json.
 */

/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/**
 * Результат проверки формата BIN/IIN: проверяется только сама строка — длина и состав
 * символов, — а НЕ то, что такой BIN реально существует. Проверка бесплатна и мгновенна.
 * Чтобы узнать, существует ли такой BIN и чей он, выполните основной запрос — он
 * возвращает карточку BinLookupResult.
 *
 *
 * Пример. Для "48334884": isValidFormat = true, normalizedBin =
 * "48334884", binLength = 8.
 */
export interface BinFormatValidationResult {
  /** Нормализованный BIN: убраны пробелы и любые разделители, оставлены только цифры. */
  normalizedBin: string;
  /**
   * true, если строка после нормализации состоит только из цифр и имеет допустимую длину
   * (6, 8 или 10 знаков). Это проверка ФОРМАТА, а не существования BIN.
   */
  isValidFormat: boolean;
  /** Длина нормализованного BIN в цифрах (для отображения и проверок разрядности). */
  binLength: number;
  /** Понятное человеку пояснение результата (что не так с форматом, либо «формат корректен»). */
  message: string;
}

/**
 * Полная карточка результата BIN Lookup одним плоским набором полей.
 * Объединяет всё, что известно про банковский идентификационный номер:
 * признак валидности, реквизиты карты (бренд/тип/категория), данные банка-эмитента и страны,
 * а также (если был передан IP клиента) результаты дополнительных антифрод-проверок по IP.
 *
 *
 * Пример. Для BIN 48334884 в карточке будет: valid = true,
 * cardBrand = "VISA", cardType = "CREDIT",
 * cardCategory = "PLATINUM", country = "NEW ZEALAND",
 * countryCode = "NZ", issuer = "KIWIBANK, LTD.".
 */
export interface BinLookupResult {
  /**
   * true, если переданный номер является валидным BIN/IIN и найден в справочнике.
   * false означает, что такого BIN в базе нет (например, опечатка или несуществующий
   * префикс) — в этом случае реквизиты карты/эмитента будут пустыми.
   */
  valid: boolean;
  /**
   * Сам BIN/IIN, по которому выполнялся поиск (только цифры, 6/8/10 знаков). По числу
   * цифр можно понять, на какой разрядности BIN основан результат (см. binLength).
   */
  binNumber: string;
  /**
   * Длина BIN в цифрах (6, 8 или 10). Вычисляется из binNumber — разрядность
   * видна сразу, без подсчёта символов вручную.
   */
  binLength: number;
  /**
   * Платёжная система (бренд) карты: например "VISA", "MASTERCARD", "AMERICAN EXPRESS",
   * "MAESTRO", "UNIONPAY", "JCB". Пусто, если бренд для BIN неизвестен.
   */
  cardBrand: string | null;
  /**
   * Тип карты по способу списания средств. Возможные значения: "DEBIT" (дебетовая),
   * "CREDIT" (кредитная), "CHARGE CARD" (карта с обязательным полным погашением).
   * Пусто, если тип неизвестен.
   */
  cardType: string | null;
  /**
   * Категория (продукт) карты. Категорий много; самые частые: "CLASSIC", "STANDARD",
   * "BUSINESS", "CORPORATE", "GOLD", "PLATINUM", "SIGNATURE", "PREPAID". Пусто, если неизвестна.
   */
  cardCategory: string | null;
  /** Полное название страны банка-эмитента (например, "NEW ZEALAND"). Пусто, если неизвестна. */
  country: string | null;
  /** Код страны эмитента в формате ISO-3166 alpha-2 (например, "NZ"). Пусто, если неизвестен. */
  countryCode: string | null;
  /** Код страны эмитента в формате ISO-3166 alpha-3 (например, "NZL"). Пусто, если неизвестен. */
  countryCode3: string | null;
  /**
   * Код валюты страны эмитента в формате ISO-4217 (например, "NZD", "USD", "EUR").
   * Полезно для оценки валюты, в которой, скорее всего, выпущена карта. Пусто, если неизвестен.
   */
  currencyCode: string | null;
  /** Название банка-эмитента карты (например, "KIWIBANK, LTD."). Пусто, если неизвестно. */
  issuer: string | null;
  /** Сайт банка-эмитента (например, "http://www.kiwibank.co.nz"). Пусто, если неизвестен. */
  issuerWebsite: string | null;
  /** Контактный телефон банка-эмитента. Пусто, если неизвестен. */
  issuerPhone: string | null;
  /**
   * true, если это коммерческая (бизнес/корпоративная) карта. Полезно при применении бизнес-правил
   * (например, разные комиссии или лимиты для корпоративных карт).
   */
  isCommercial: boolean;
  /** true, если это предоплаченная (prepaid) карта. */
  isPrepaid: boolean;
  /**
   * true, если карту можно пополнять (reloadable). В основном помогает отличать
   * одноразовые предоплаченные карты от пополняемых.
   */
  isReloadable: boolean;
  /**
   * Был ли в запросе передан IP клиента (и, соответственно, заполнен ли антифрод-блок ниже).
   * Если false — все IP-поля носят дефолтные значения и их не нужно учитывать.
   */
  hasCustomerIp: boolean;
  /**
   * true, если страна IP-адреса клиента совпадает со страной банка-эмитента карты. Несовпадение —
   * один из признаков повышенного риска (карта одной страны, а платёж идёт из другой). Имеет смысл,
   * только когда hasCustomerIp = true.
   */
  ipMatchesBin: boolean;
  /** Страна IP-адреса клиента (если IP был передан и определён). Иначе пусто. */
  ipCountry: string | null;
  /** Код страны IP клиента в формате ISO-3166 alpha-2. Иначе пусто. */
  ipCountryCode: string | null;
  /** Код страны IP клиента в формате ISO-3166 alpha-3. Иначе пусто. */
  ipCountryCode3: string | null;
  /** Регион IP клиента (если удалось определить). Иначе пусто. */
  ipRegion: string | null;
  /** Город IP клиента (если удалось определить). Иначе пусто. */
  ipCity: string | null;
  /**
   * true, если IP клиента числится в одном из списков блокировок (известные источники
   * мошенничества, спама, бот-сетей, прокси и т.п.). Сильный признак риска. Имеет смысл,
   * только когда hasCustomerIp = true.
   */
  ipBlocklisted: boolean;
  /**
   * Список конкретных списков блокировок, в которых найден IP клиента (если найден).
   * Пусто, если IP не передан, не в списках или их состав неизвестен.
   */
  ipBlocklists: string[];
  /** Время выполнения запроса в миллисекундах. */
  elapsedMs: number;
}

/** Необязательные параметры метода `lookup`. */
export interface LookupParams {
  /**
   * (Необязательно) IP-адрес клиента. Если передан — в ответ добавятся антифрод-данные по IP
   * (страна/город, совпадение страны IP со страной карты, проверка по спискам блокировок).
   */
  customerIp?: string;
}
