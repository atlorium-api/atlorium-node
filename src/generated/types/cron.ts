/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/** Параметры, из которых собирается cron-выражение. */
export interface CronBuildRequest {
  /**
   * Заготовка расписания. От неё зависит, какие из остальных полей вообще учитываются:
   * интервал нужен только шаблонам с шагом, дни недели — недельному, число месяца — месячному.
   */
  template: CronTemplateType;
  /**
   * Шаг для шаблонов «каждые N минут» и «каждые N часов»; остальными шаблонами игнорируется.
   * Пример: шаблон «каждые N минут» с интервалом 15 даёт в поле минут *\/15.
   */
  interval: number;
  /**
   * Время суток для суточного, недельного и месячного расписаний. Например, 09:30 —
   * запуск в половине десятого утра.
   */
  timeOfDay: string;
  /**
   * Число месяца (1–31) для месячного расписания. Учитывайте короткие месяцы: 31-е число
   * пропустит февраль, апрель, июнь, сентябрь и ноябрь.
   */
  dayOfMonth: number;
  /**
   * Дни недели для недельного расписания. Можно выбрать несколько — запуск произойдёт
   * в каждый из них.
   */
  weekDays: DayOfWeek[];
  /**
   * Добавлять ли в выражение поле секунд. true даёт шесть полей (диалект Quartz),
   * false — классические пять полей Unix cron. Выбирать нужно по тому планировщику,
   * куда выражение потом вставят: лишнее поле секунд он разберёт неверно.
   */
  includeSeconds: boolean;
}

/** Результат сборки cron-строки. */
export interface CronBuildResult {
  /** Готовое cron-выражение. Пустая строка, если собрать не удалось. */
  expression: string;
  /**
   * Замечания к собранному расписанию: оно рабочее, но сработает не всегда так, как ждут.
   * Пример: выбрано 31-е число — в коротких месяцах запуска не будет.
   */
  warnings: string[];
  /**
   * Причина, по которой выражение собрать не удалось: недопустимый интервал,
   * не выбран ни один день недели. Пустая строка при успехе.
   */
  error: string;
  /** Удалось ли собрать выражение. Вычисляется по пустоте error. */
  success: boolean;
}

/** Запрос на оценку cron-выражения через API. */
export interface CronEvaluateRequest {
  /** Cron-выражение (5 или 6 полей, допускается ? из Quartz). */
  expression: string;
  /** Часовой пояс для расчёта (Id из TimeZoneInfo). */
  timeZoneId: string;
  /** Стартовая точка расчёта (UTC). Если не задана — сейчас. */
  fromUtc: string | null;
  /** Количество ближайших запусков (1-100). */
  take: number;
}

/** Результат разбора и оценки cron-выражения. */
export interface CronEvaluationResult {
  /**
   * Разобралось ли выражение. При false причина лежит в error,
   * а список ближайших запусков будет пустым.
   */
  isValid: boolean;
  /** Выражение ровно в том виде, в каком его прислали, — без правок и нормализации. */
  rawExpression: string;
  /**
   * Приведённое к единому виду выражение: подставлены пропущенные поля, знак ?
   * из диалекта Quartz заменён на *, лишние пробелы убраны. Именно эту строку
   * стоит сохранять у себя — она означает то же самое, но читается однозначно.
   */
  normalizedExpression: string;
  /**
   * Причина, по которой выражение признано некорректным: неверное число полей,
   * значение вне диапазона, нераспознанный символ. Пустая строка при успешном разборе.
   */
  error: string;
  /**
   * Предупреждения о выражении, которое формально верно, но почти наверняка сработает
   * не так, как задумано. Пример: запуск 31-го числа — в феврале, апреле, июне, сентябре
   * и ноябре его не будет вовсе. Наличие предупреждений НЕ делает выражение недействительным.
   */
  warnings: string[];
  /**
   * Пояснение к каждому полю выражения по-человечески: «минуты: каждые 15»,
   * «день недели: понедельник». Порядок совпадает с порядком полей
   * в normalizedExpression.
   */
  segments: string[];
  /**
   * Ближайшие моменты срабатывания расписания, по возрастанию. Считаются в часовом поясе
   * timeZone, поэтому переход на летнее время уже учтён. Сколько запусков
   * вернуть — задаётся в запросе.
   */
  occurrences: string[];
  /**
   * Часовой пояс, в котором посчитаны запуски. Одно и то же выражение в разных поясах
   * срабатывает в разное время, поэтому пояс возвращается вместе с результатом.
   */
  timeZone: TimeZoneInfo;
}

/**
 * Типовая заготовка расписания для простого конструктора.
 *
 * Значения:
 * * `EveryMinute` — Каждую минуту.
 * * `EveryNMinutes` — Каждые N минут; шаг задаётся полем интервала.
 * * `Hourly` — Раз в час, в начале часа.
 * * `EveryNHours` — Каждые N часов; шаг задаётся полем интервала.
 * * `Daily` — Раз в сутки, в заданное время.
 * * `Weekly` — В выбранные дни недели, в заданное время.
 * * `Monthly` — Раз в месяц, в заданное число и время.
 */
export const CronTemplateType = {
  /** Каждую минуту. */
  EveryMinute: 0,
  /** Каждые N минут (шаг — `interval`). */
  EveryNMinutes: 1,
  /** Раз в час, в начале часа. */
  Hourly: 2,
  /** Каждые N часов (шаг — `interval`). */
  EveryNHours: 3,
  /** Раз в сутки, в `timeOfDay`. */
  Daily: 4,
  /** В выбранные дни недели (`weekDays`), в `timeOfDay`. */
  Weekly: 5,
  /** Раз в месяц: число `dayOfMonth`, время `timeOfDay`. */
  Monthly: 6,
} as const;
/**
 * Типовая заготовка расписания для простого конструктора.
 *
 * Значения:
 * * `EveryMinute` — Каждую минуту.
 * * `EveryNMinutes` — Каждые N минут; шаг задаётся полем интервала.
 * * `Hourly` — Раз в час, в начале часа.
 * * `EveryNHours` — Каждые N часов; шаг задаётся полем интервала.
 * * `Daily` — Раз в сутки, в заданное время.
 * * `Weekly` — В выбранные дни недели, в заданное время.
 * * `Monthly` — Раз в месяц, в заданное число и время.
 */
export type CronTemplateType = (typeof CronTemplateType)[keyof typeof CronTemplateType];

