export interface TimeZoneInfo {
  /** Идентификатор часового пояса. Единственное поле, которое стоит использовать в коде: именно его принимают и наши методы, и планировщики задач. Примеры: «Russian Standard Time» (нотация Windows), «Europe/Moscow» (нотация IANA). */
  id: string | null;
  /** Записан ли идентификатор в нотации IANA (Europe/Moscow), а не Windows. */
  hasIanaId: boolean;
  /** Человекочитаемое название пояса со смещением. Язык названия зависит от настроек сервера, поэтому опираться на него в коде нельзя. */
  displayName: string | null;
  /** Название стандартного (зимнего) времени пояса. */
  standardName: string | null;
  /** Название летнего времени пояса. У поясов без перевода часов совпадает со стандартным. */
  daylightName: string | null;
  /** Базовое смещение относительно UTC без учёта перевода часов, в формате «часы:минуты:секунды». Для Москвы — «03:00:00». */
  baseUtcOffset: string;
  /** Переводятся ли в этом поясе часы на летнее время. В России — нет; для поясов, где перевод есть, время запусков в расписании сдвигается дважды в год. */
  supportsDaylightSavingTime: boolean;
}

