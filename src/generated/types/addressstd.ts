/**
 * Типы запросов и ответов сервиса «API стандартизации адреса».
 *
 * СГЕНЕРИРОВАНО scripts/generate.mjs — не редактировать руками. Источник: spec/addressstd_ru.json.
 */

/**
 * Один разобранный элемент адреса. text — уже нормализованное человеко-читаемое
 * представление элемента (например, «улица 16 Парковая», «д.2 корп.1»); остальные поля дают ту же
 * информацию в разобранном виде для программной обработки/сопоставления. Незаполненные поля = null.
 */
export interface AddressComponent {
  /** Адресный уровень элемента. */
  level: AddressLevel;
  /** Человеко-читаемое название уровня по-русски («Улица», «Дом/здание», …). */
  levelTitle: string;
  /** Нормализованное представление элемента одной строкой. */
  text: string;
  /**
   * Типы элемента (для «площадных» уровней страна…улица): например [«улица»], [«город»].
   * Для дома/помещения — тип дома/помещения, если удалось выделить. Может быть null.
   */
  types: string[] | null;
  /** Собственные имена элемента (например [«16», «Парковая»]). Может быть null. */
  names: string[] | null;
  /** Основной номер элемента (номер дома, участка, квартиры, комнаты). Может быть null. */
  number: string | null;
  /** Корпус — только для домов/зданий. Может быть null. */
  buildNumber: string | null;
  /** Строение/сооружение — только для домов/зданий. Может быть null. */
  structNumber: string | null;
  /** Номер земельного участка — когда элемент дома привязан к участку. Может быть null. */
  plotNumber: string | null;
  /** Второстепенные значения (уточнения, имена персон в честь кого назван объект и т.п.). Может быть null. */
  misc: string[] | null;
}

/**
 * Адресный уровень элемента. Значения и порядок повторяют модель уровней ГАР/ФИАС:
 * сверху вниз — от страны к комнате.
 *
 * Значения:
 * * `Undefined` — Уровень не определён.
 * * `Country` — Страна.
 * * `RegionArea` — Регион (область, республика, край).
 * * `RegionCity` — Город федерального значения (Москва, Санкт-Петербург, Севастополь).
 * * `District` — Административный/муниципальный район.
 * * `Settlement` — Городское/сельское поселение.
 * * `City` — Город.
 * * `CityDistrict` — Район города (устаревший уровень ГАР).
 * * `Locality` — Населённый пункт (посёлок, село, деревня).
 * * `Territory` — Элемент планировочной структуры (квартал, территория, СНТ).
 * * `Street` — Элемент улично-дорожной сети (улица, проспект, переулок).
 * * `Plot` — Земельный участок.
 * * `Building` — Здание/дом (с корпусом и строением).
 * * `Apartment` — Помещение/квартира.
 * * `Room` — Комната.
 */
export type AddressLevel = 'Undefined' | 'Country' | 'RegionArea' | 'RegionCity' | 'District' | 'Settlement' | 'City' | 'CityDistrict' | 'Locality' | 'Territory' | 'Street' | 'Plot' | 'Building' | 'Apartment' | 'Room';

/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/**
 * Привязка разобранного адреса к объекту государственного адресного реестра (ГАР/ФИАС):
 * идентификаторы объекта и связанные с ним коды — почтовый индекс, КЛАДР, ОКТМО, ОКАТО.
 *
 * В текущей версии сервиса объект не заполняется: доступен базовый разбор адресной строки.
 * Поле присутствует в контракте заранее, чтобы подключение привязки не потребовало
 * несовместимых изменений ответа.
 */
export interface GarBinding {
  /** GUID объекта ГАР. */
  guid: string | null;
  /** Числовой ObjectId объекта ГАР. */
  objectId: number | null;
  /** Код КЛАДР. */
  kladrCode: string | null;
  /** Почтовый индекс. */
  postIndex: string | null;
  /** ОКТМО. */
  oktmo: string | null;
  /** ОКАТО. */
  okato: string | null;
}

export interface GeoPoint {
  lat: number;
  lon: number;
}

/**
 * Итог стандартизации одной адресной строки: разобранные элементы адреса, нормализованная
 * запись и коэффициент качества разбора.
 */
export interface StandardizedAddress {
  /** Исходная строка (эхо запроса). */
  input: string;
  /** Нормализованный адрес одной строкой (собран из разобранных элементов). */
  normalized: string;
  /**
   * Коэффициент качества разбора, 0..100. 100 — идеальный разбор без лишних фрагментов; ≥90 —
   * нормально; ниже 80 — к результату стоит относиться осторожно. Оценивается именно разбор
   * строки: сверка с адресными реестрами на коэффициент не влияет.
   */
  quality: number;
  /** Код страны (RU/EN/US…), если удалось определить. Может быть null. */
  countryCode: string | null;
  /** Сообщение о неточности/проблеме, влияющей на качество (например, непонятный фрагмент). Может быть null. */
  message: string | null;
  /** Информационное сообщение, НЕ влияющее на качество. Может быть null. */
  info: string | null;
  /** Разобранные элементы адреса, сверху вниз (от страны к квартире). */
  components: AddressComponent[];
  /**
   * Второстепенные элементы, не вписавшиеся в общую модель (этаж, а/я, очередь, индекс из текста,
   * нормализованное название организации). Ключ — тип элемента, значение — строка. Может быть null.
   */
  extra: Record<string, string> | null;
  /** Время разбора в миллисекундах. */
  milliseconds: number;
  /**
   * Привязка к государственному адресному реестру (ГАР/ФИАС). В текущей версии сервиса
   * всегда null: доступен базовый разбор строки.
   */
  gar: GarBinding | null;
  /**
   * Географические координаты адреса. В текущей версии сервиса всегда null: доступен
   * базовый разбор строки.
   */
  geo: GeoPoint | null;
}

/** Необязательные параметры метода `standardize`. */
export interface StandardizeParams {
  /**
   * Код региона по умолчанию (2 цифры, например 77), если в строке регион не указан — помогает
   * разобрать «улица + дом» без верхнего уровня. Необязателен.
   */
  region?: number;
  /**
   * Дополнить разбор привязкой к государственному адресному реестру (ГАР/ФИАС).
   * Режим готовится к запуску: сейчас запрос с этим флагом возвращает 501 и не тарифицируется.
   * После запуска будет тарифицироваться дополнительно к базовому разбору.
   */
  bind?: boolean;
  /**
   * Дополнить разбор географическими координатами адреса.
   * Режим готовится к запуску: сейчас запрос с этим флагом возвращает 501 и не тарифицируется.
   * После запуска будет тарифицироваться дополнительно к базовому разбору.
   */
  geocode?: boolean;
}
