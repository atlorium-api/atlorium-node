/**
 * Типы запросов и ответов сервиса «API прямого геокодинга».
 *
 * СГЕНЕРИРОВАНО scripts/generate.mjs — не редактировать руками. Источник: spec/geocodeforward_ru.json.
 */

/** Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться. */
export interface ApiError {
  /**
   * Машинный код причины отказа. Возможные значения:
   *
   * * `server_error` (500) — Сервис временно недоступен
   * * `unauthorized` (401) — Требуется вход
   * * `api_key_required` (401) — Нужен API-ключ
   * * `account_not_activated` (402) — Аккаунт не активирован
   * * `rate_limited_client` (429) — Слишком много запросов
   * * `rate_limited_global` (429) — Высокая нагрузка на сервис
   * * `provider_keys_exhausted` (429) — Сервис временно недоступен
   * * `insufficient_credits` (402) — Недостаточно кредитов
   * * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
   * * `service_disabled` (503) — Проводятся плановые работы
   * * `maintenance` (503) — Проводятся плановые работы
   * * `guest_not_allowed` (402) — Нужна регистрация
   * * `service_not_in_account_terms` (403) — Сервис не подключён
   * * `bad_request` (400) — Некорректный запрос
   * * `forbidden` (403) — Доступ запрещён
   * * `not_found` (404) — Ничего не найдено
   * * `method_not_allowed` (405) — Метод HTTP не поддерживается
   * * `unsupported_media_type` (415) — Формат запроса не поддерживается
   * * `not_implemented` (501) — Режим пока не реализован
   */
  error: string;
  /** Короткий заголовок для интерфейса. */
  title: string;
  /** Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком. */
  message: string;
  /** Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null. */
  balance: number | null;
  /** Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты). */
  retryAfterSeconds: number | null;
  /** Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды. */
  retryAfterText: string | null;
}

/** Административная иерархия объекта ИЗ РЕЕСТРА: что записано в его официальном адресе. */
export interface GeocodeAdminHierarchy {
  /** Субъект Российской Федерации — область, край, республика, город федерального значения. */
  region: string | null;
  /** Район субъекта или муниципальное образование — так, как записано в реестре. */
  county: string | null;
  /** Населённый пункт — город, посёлок, село. */
  locality: string | null;
  /** Улица (или иной адресообразующий элемент: проспект, переулок, микрорайон). */
  street: string | null;
  /** true, если не заполнен ни один уровень — иерархии по объекту нет. */
  isEmpty: boolean;
}

/** Результат геокодирования одной строки в пакетном запросе. */
export interface GeocodeBatchItem {
  /**
   * Исходная строка. Возвращается вместе с результатом, потому что склейка по позиции в массиве —
   * первое, что ломается при обработке пакета, и ломается молча.
   */
  query: string;
  /**
   * Найденные варианты. ПУСТОЙ СПИСОК — нормальный исход для отдельной строки: он означает
   * «этот адрес не найден» и не оплачивается.
   */
  matches: GeocodeMatch[];
}

/** Запрос пакетного прямого геокодинга: много адресов за один вызов. */
export interface GeocodeBatchRequest {
  /**
   * Адресные строки в том порядке, в каком их нужно вернуть. Пустые и бессмысленные элементы
   * пакет не обрывают: у них будет свой результат с пустым списком совпадений.
   */
  queries: string[];
  /** Сколько вариантов возвращать на каждую строку. По умолчанию один — самый вероятный. */
  sizePerQuery: number;
  /** Отдавать только точные попадания в дом. См. exactOnly. */
  exactOnly: boolean;
}

/** Ответ пакетного прямого геокодинга. */
export interface GeocodeBatchResponse {
  /**
   * Результаты СТРОГО в порядке запроса, по одному на каждую присланную строку. Порядок
   * гарантирован: клиент почти всегда склеивает результат со своей таблицей по позиции.
   */
  items: GeocodeBatchItem[];
  /** Сколько строк было прислано. */
  requested: number;
  /** Для скольких строк нашёлся хотя бы один вариант. */
  found: number;
  /**
   * Сколько единиц работы списано. Равно числу НАЙДЕННЫХ строк: ненайденные в пакете
   * бесплатны так же, как поодиночке.
   */
  billedUnits: number;
  /** Строка указания источника данных. Отображать обязательно. */
  attribution: string;
}

/**
 * Граница административного образования в формате GeoJSON — чтобы нарисовать её на своей карте
 * или самостоятельно проверять попадание точек внутрь, не обращаясь к нам на каждую точку.
 */
export interface GeocodeBoundary {
  /** Идентификатор образования. */
  placeId: string;
  /** Название с типом: «г Казань», «Вахитовский р-н». */
  name: string;
  /** Полная подпись объекта, включая вышестоящие уровни. */
  label: string | null;
  /** Уровень в иерархии реестра: 1 — субъект РФ, 2–4 — районы, 5–6 — населённые пункты. */
  level: number | null;
  /**
   * Площадь в квадратных километрах, посчитанная по сфероиду. Первая и самая дешёвая проверка
   * того, что вернулось ожидаемое образование, а не однофамилец в другом регионе.
   */
  areaKm2: number | null;
  /** Центр образования — точка, к которой относят объект в целом. */
  center: GeoPoint | null;
  /**
   * Сама геометрия в GeoJSON: Polygon или MultiPolygon с координатами в порядке
   * [долгота, широта] — так требует стандарт GeoJSON, и это единственное место контракта, где
   * порядок именно такой.
   */
  geometry: JsonElement;
  /**
   * Постоянная оговорка об упрощении геометрии. Отдаётся всегда: клиент, который об этом не
   * знает, рано или поздно сделает по границе юридически значимый вывод.
   */
  simplificationNotice: string;
}

/** Ответ прямого геокодинга. */
export interface GeocodeForwardResponse {
  /** Запрос в том виде, в каком он ушёл в поиск, — удобно для отладки на стороне клиента. */
  query: string;
  /**
   * Найденные варианты, самый вероятный первым. Пустым не бывает: пустой результат не доходит до
   * клиента как успешный.
   */
  matches: GeocodeMatch[];
  /** Строка указания источника данных. Отображать обязательно — этого требует лицензия. */
  attribution: string;
}

/**
 * Один найденный адресный объект: координаты, разобранный адрес, реестровая иерархия и —
 * обязательно — уровень точности координаты.
 */
export interface GeocodeMatch {
  /** Стабильный идентификатор объекта в государственном реестре адресов. */
  placeId: string | null;
  /** Готовая однострочная запись адреса — то, что показывают пользователю. */
  label: string | null;
  /** Собственное имя объекта: название улицы или номер дома, смотря что найдено. */
  name: string | null;
  /** Номер дома вместе с корпусом или строением, если они есть. */
  houseNumber: string | null;
  /** Улица (или иной адресообразующий элемент). */
  street: string | null;
  /** Почтовый индекс из реестра. */
  postalCode: string | null;
  /** Координаты объекта. */
  point: GeoPoint;
  /**
   * Что именно найдено: address — дом, street — улица, locality —
   * населённый пункт, county — район, region — субъект РФ.
   */
  layer: string;
  /** Чья это координата. См. GeocodePrecision. */
  precision: GeocodePrecision;
  /** Административная иерархия объекта из реестра. */
  admin: GeocodeAdminHierarchy | null;
  /**
   * Идентификатор родительского объекта: для дома — улица или населённый пункт, для улицы —
   * населённый пункт. По нему запрашивается граница вышестоящего образования.
   */
  parentPlaceId: string | null;
  /**
   * Расстояние от запрошенной точки до объекта, километры. Заполняется только там, где запрос
   * был точкой, — в обратном геокодинге.
   */
  distanceKm: number | null;
}

/** Ответ режима «карточка объекта по идентификатору». */
export interface GeocodePlaceResponse {
  /** Запрошенный идентификатор. */
  placeId: string;
  /** Карточка объекта. */
  place: GeocodeMatch;
  /**
   * Граница объекта в GeoJSON. Заполнена, только если её запросили И объект её имеет:
   * у дома и улицы границы нет.
   */
  boundary: GeocodeBoundary | null;
  /** Сколько единиц работы списано: карточка плюс граница, если она вернулась. */
  billedUnits: number;
  /** Строка указания источника данных. Отображать обязательно. */
  attribution: string;
}

/** Ответ режима «что относится к почтовому индексу». */
export interface GeocodePostcodeResponse {
  /** Запрошенный индекс. */
  code: string;
  /**
   * Адресообразующие объекты с этим индексом, от общего к частному. Дома в выдачу не попадают:
   * их на один индекс десятки тысяч, и такой ответ не отвечает на заданный вопрос.
   */
  places: GeocodeMatch[];
  /** Строка указания источника данных. Отображать обязательно. */
  attribution: string;
}

/**
 * Чья это координата — то есть насколько точно она указывает на запрошенный объект. Поле
 * обязательное к прочтению: одна и та же пара чисел с разным уровнем точности означает
 * совершенно разное.
 *
 * Значения:
 * * `Exact` — Координата ЭТОГО САМОГО дома, взятая из данных. Годится для любой задачи, включая доставку до подъезда.
 * * `Range` — Номер дома ВЫЧИСЛЕН, а не найден: геокодер знает координаты соседних домов на улице и расположил искомый между ними — либо совпадение оказалось неполным (спрашивали «13к2», в реестре дом заведён одной записью «13»). Практический смысл: попасть на нужную сторону улицы и в нужный квартал такой результат позволяет, указать конкретное здание — нет.
 * * `Street` — Дома в данных нет — отдан центр улицы. Осмысленный ответ («улица найдена, дом не заведён»), но для навигации до подъезда непригоден.
 * * `Locality` — Улицы в данных нет — отдан центр населённого пункта. Как адрес это уже не читается: «где-то в этом городе».
 * * `Area` — Отдан центр района или региона. Самый грубый из содержательных уровней.
 * * `None` — Уровень неизвестен — координате верить нельзя. Такие объекты до клиента не доходят; значение существует, чтобы неизвестное не трактовалось молча как точное.
 */
export type GeocodePrecision = 'exact' | 'range' | 'street' | 'locality' | 'area' | 'none';

export interface GeoPoint {
  latitude: number;
  longitude: number;
}

export type JsonElement = unknown;

/** Необязательные параметры метода `search`. */
export interface SearchParams {
  /**
   * Сколько вариантов вернуть. Значения за пределами допустимого диапазона подтягиваются к
   * границе, а не считаются ошибкой.
   */
  size?: number;
  /**
   * Оставить только точные попадания в дом (precision = exact), отбросив всё остальное.
   * По умолчанию выключено.
   */
  exactOnly?: boolean;
}

/** Необязательные параметры метода `searchStructured`. */
export interface SearchStructuredParams {
  /** Улица с номером дома. Пример: улица Баумана, 13 */
  address?: string;
  /** Населённый пункт. Пример: Казань */
  locality?: string;
  /** Субъект Российской Федерации. Пример: Республика Татарстан */
  region?: string;
  /** Почтовый индекс. Пример: 420111 */
  postalCode?: string;
  /** Сколько вариантов вернуть. */
  size?: number;
  /** Оставить только точные попадания в дом. По умолчанию выключено. */
  exactOnly?: boolean;
}

/** Необязательные параметры метода `searchBatch`. */
export interface SearchBatchParams {
  /** Сколько вариантов возвращать на каждую строку. По умолчанию один — самый вероятный. */
  sizePerQuery?: number;
  /** Отдавать только точные попадания в дом. См. exactOnly. */
  exactOnly?: boolean;
}

/** Необязательные параметры метода `getPlace`. */
export interface GetPlaceParams {
  /**
   * Вернуть также границу объекта в GeoJSON. Стоит дополнительную единицу работы, и только
   * если граница действительно вернулась.
   */
  includeBoundary?: boolean;
}

/** Необязательные параметры метода `searchPostcode`. */
export interface SearchPostcodeParams {
  /** Сколько объектов вернуть. */
  size?: number;
}
