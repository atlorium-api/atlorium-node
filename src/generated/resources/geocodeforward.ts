import { APIResource, type FinalRequestOptions, type RequestOptions, stripNullish, toList } from '../../core/base-client';
import type { ApiResponse } from '../../core/response';
import type * as T from '../types/geocodeforward';

function searchRequest(text: string, params: T.SearchParams & RequestOptions): FinalRequestOptions {
  const { size, exactOnly, ...options } = params;
  return {
    ...options,
    method: 'GET',
    path: '/api/geocodeforward',
    query: { text, size, exactOnly },
  };
}

function searchStructuredRequest(params: T.SearchStructuredParams & RequestOptions): FinalRequestOptions {
  const { address, locality, region, postalCode, size, exactOnly, ...options } = params;
  return {
    ...options,
    method: 'GET',
    path: '/api/geocodeforward/structured',
    query: { address, locality, region, postalCode, size, exactOnly },
  };
}

function searchBatchRequest(queries: string | readonly string[], params: T.SearchBatchParams & RequestOptions): FinalRequestOptions {
  const { sizePerQuery, exactOnly, ...options } = params;
  return {
    ...options,
    method: 'POST',
    path: '/api/geocodeforward/batch',
    body: stripNullish({ queries: toList(queries), sizePerQuery, exactOnly }),
    hasBody: true,
  };
}

function getPlaceRequest(placeId: string, params: T.GetPlaceParams & RequestOptions): FinalRequestOptions {
  const { includeBoundary, ...options } = params;
  return {
    ...options,
    method: 'GET',
    path: '/api/geocodeforward/place',
    query: { placeId, includeBoundary },
  };
}

function searchPostcodeRequest(code: string, params: T.SearchPostcodeParams & RequestOptions): FinalRequestOptions {
  const { size, ...options } = params;
  return {
    ...options,
    method: 'GET',
    path: '/api/geocodeforward/postcode',
    query: { code, size },
  };
}

